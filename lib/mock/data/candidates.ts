/**
 * Fonction de sanitization côté serveur :
 * Transforme un enregistrement candidat brut en DTO aveugle pur.
 * Aucune PII (prénom, nom, email, téléphone, adresse, entreprises réelles) ne passe dans le DTO aveugle.
 */
export function sanitizeToBlindDto(record: MockCandidateRecord): CvDocumentBlindDto {
  return {
    id: record.id,
    pseudonym: record.pseudonym,
    isAnonymized: true,
    hashId: record.hashId,
    currentTitle: record.currentTitle,
    yearsExperience: record.yearsExperience,
    seniorityLevel: record.seniorityLevel,
    location: record.location,
    skills: [...record.skills],
    experienceSummary: record.experienceSummary,
    experiences: record.experiences.map((exp) => ({ ...exp })),
    education: record.education.map((edu) => ({ ...edu })),
    availability: record.availability,
    targetSalary: record.targetSalary,
    aiMatchScore: record.aiMatchScore,
    aiConfidence: record.aiConfidence,
    aiJustification: record.aiJustification,
    gapAnalysis: {
      strongCriteria: [...record.gapAnalysis.strongCriteria],
      partialCriteria: [...record.gapAnalysis.partialCriteria],
      missingCriteria: [...record.gapAnalysis.missingCriteria],
    },
    vectorCluster: record.vectorCluster,
    vectorCoords2D: record.vectorCoords2D ? { ...record.vectorCoords2D } : undefined,
    redactedPdfUrl: record.redactedPdfUrl,
    anomalies: record.anomalies.map((a) => ({ ...a })),
    folderId: record.folderId,
    rgpdStatus: record.rgpdStatus,
    retentionDeadline: record.retentionDeadline,
    createdAt: record.createdAt,
  };
}

/**
 * Fonction de levée d'anonymat côté serveur :
 * Génère le DTO complet nominatif UNIQUEMENT après vérification du contexte d'autorisation.
 */
export function unmaskToFullDto(
  record: MockCandidateRecord,
  actorId: string,
  actorName: string,
  reason: string,
): CvDocumentFullDto {
  const blind = sanitizeToBlindDto(record);
  const now = new Date();
  const expiresAt = new Date(now.getTime() + 24 * 60 * 60 * 1000).toISOString(); // Accès nominatif limité à 24h

  return {
    ...blind,
    isAnonymized: false,
    firstName: record._piiServerOnly.firstName,
    lastName: record._piiServerOnly.lastName,
    email: record._piiServerOnly.email,
    phone: record._piiServerOnly.phone,
    fullAddress: record._piiServerOnly.fullAddress,
    originalCompanies: [...record._piiServerOnly.originalCompanies],
    originalInstitutions: [...record._piiServerOnly.originalInstitutions],
    originalPdfUrl: record._piiServerOnly.originalPdfUrl,
    unmaskJustification: {
      actorId,
      actorName,
      reason,
      unmaskedAt: now.toISOString(),
      expiresAt,
    },
  };
}
