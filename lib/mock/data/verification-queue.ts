export function computeVerificationStats(items: VerificationItem[]): VerificationStats {
  const total = items.length;
  const treated = items.filter((i) => i.status === 'treated').length;
  const pending = items.filter((i) => i.status === 'pending' || i.status === 'in_progress').length;
  const excluded = items.filter((i) => i.status === 'excluded').length;
  const suspiciousCount = items.filter((i) => i.motif === 'contenu_suspect').length;

  return {
    total,
    treated,
    pending,
    excluded,
    suspiciousCount,
  };
}
